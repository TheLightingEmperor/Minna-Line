// Runs schema.sql + community.sql in an in-memory Postgres and checks the community's access rules.
import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
const read = (f) => fs.readFileSync(new URL('../supabase/' + f, import.meta.url), 'utf8');
const db = new PGlite();
let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => { cond ? pass++ : fail++; console.log((cond ? 'PASS ' : 'FAIL ') + name + (extra ? '  → ' + extra : '')); };
const as = async (role, uid) => { await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid || ''}', false); ${role ? `set role ${role};` : ''}`); };
const q = async (sql) => (await db.query(sql)).rows;
const fails = async (name, sql, want) => { try { const r = await db.query(sql); ok(name, false, 'expected error, got ' + JSON.stringify(r.rows).slice(0, 100)); } catch (e) { ok(name, !want || want.test(e.message), e.message.slice(0, 80)); } };
await db.exec(`
  create role anon nologin; create role authenticated nologin;
  create schema auth;
  create table auth.users (id uuid primary key default gen_random_uuid(), email text, raw_user_meta_data jsonb, created_at timestamptz default now());
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema auth, public to anon, authenticated;
  grant execute on function auth.uid() to anon, authenticated;
  alter default privileges in schema public grant all on tables to anon, authenticated;
  alter default privileges in schema public grant execute on functions to anon, authenticated;
`);
await db.exec(read('schema.sql')); await db.exec(read('community.sql')); await db.exec(read('community.sql'));
ok('community.sql runs twice', true);
const mk = async (email, name) => (await q(`insert into auth.users (email, raw_user_meta_data) values ('${email}', '{"display_name":"${name}"}') returning id`))[0].id;
const A = await mk('aiko@example.com', 'Aiko'), B = await mk('ben@example.com', 'Ben'), C = await mk('staff@example.com', 'Staff');
await q(`insert into public.admins (user_id) values ('${C}')`);

await as('authenticated', A);
const [p1] = await q(`insert into public.community_posts (author_id, category, jlpt, title, body) values ('${A}', 'question', 'N5', 'は or が?', 'When do I use each one?') returning id`);
ok('A posts a question', !!p1.id);
await fails('A cannot post as B', `insert into public.community_posts (author_id, category, title, body) values ('${B}', 'lounge', 'spoof', 'x')`);
await fails('A cannot post announcements', `insert into public.community_posts (author_id, category, title, body) values ('${A}', 'news', 'Fake news', 'x')`, /staff/);
await fails('A cannot set pinned on insert', `insert into public.community_posts (author_id, category, title, body, pinned) values ('${A}', 'lounge', 'pin me', 'x', true)`);
await fails('A cannot fake like_count', `update public.community_posts set like_count = 999 where id = ${p1.id}`);
await fails('title too short is refused', `insert into public.community_posts (author_id, category, title, body) values ('${A}', 'lounge', 'a', 'x')`);
ok('A edits own post', (await db.query(`update public.community_posts set title = 'は or が? (edited)' where id = ${p1.id}`)).affectedRows === 1);

await as('authenticated', B);
ok("B cannot edit A's post", (await db.query(`update public.community_posts set title = 'hacked' where id = ${p1.id}`)).affectedRows === 0);
ok("B cannot delete A's post", (await db.query(`delete from public.community_posts where id = ${p1.id}`)).affectedRows === 0);
const [c1] = await q(`insert into public.community_comments (post_id, author_id, body) values (${p1.id}, '${B}', 'は marks the topic.') returning id`);
const [c2] = await q(`insert into public.community_comments (post_id, parent_id, author_id, body) values (${p1.id}, ${c1.id}, '${B}', 'が marks the subject.') returning id`);
const [c3] = await q(`insert into public.community_comments (post_id, parent_id, author_id, body) values (${p1.id}, ${c2.id}, '${B}', 'reply to a reply') returning parent_id`);
ok('replies stay one level deep', Number(c3.parent_id) === Number(c1.id));
let r = (await q(`select public.community_like(${p1.id}, null) as r`))[0].r;
ok('B likes the post', r.liked === true && r.count === 1);
await fails('B cannot insert likes directly', `insert into public.community_likes (user_id, post_id) values ('${B}', ${p1.id})`);
await q(`insert into public.community_reports (reporter_id, post_id, reason) values ('${B}', ${p1.id}, 'test report')`);
ok('B cannot read reports', (await q(`select * from public.community_reports`)).length === 0);
await fails('B is not staff', `select public.community_moderate('post', '${p1.id}', 'pin')`, /admins only/);

await as('authenticated', A);
ok('unread replies for A', (await q(`select public.community_unread() n`))[0].n === 3);
await q(`select public.community_mark_seen()`);
ok('mark seen clears unread', (await q(`select public.community_unread() n`))[0].n === 0);
let feed = await q(`select * from public.community_feed(null, 'hot', 30, 0, null)`);
ok('feed shows counts and author, no ids or emails', feed.length === 1 && feed[0].comment_count === 3 && feed[0].like_count === 1 && feed[0].author_name === 'Aiko' && feed[0].is_mine === true && feed[0].liked === false && !('author_id' in feed[0]) && !('email' in feed[0]), JSON.stringify(Object.keys(feed[0])).slice(0, 80));
ok('kudos went to the author', (await q(`select kudos from public.profiles where id = '${A}'`))[0].kudos === 1);
const th = (await q(`select public.community_thread(${p1.id}) t`))[0].t;
ok('thread returns post + comments', th.post.title.includes('edited') && th.comments.length === 3 && th.comments[0].author_name === 'Ben' && th.post.author_id === null, 'author_id for non-admin: ' + th.post.author_id);
await q(`select public.community_like(null, ${c1.id})`);
ok('A likes a comment', (await q(`select like_count from public.community_comments where id = ${c1.id}`))[0].like_count === 1);
await as('authenticated', B);
r = (await q(`select public.community_like(${p1.id}, null) as r`))[0].r;
ok('B un-likes', r.liked === false && r.count === 0);

// staff
await as('authenticated', C);
const [n1] = await q(`insert into public.community_posts (author_id, category, title, body) values ('${C}', 'news', 'Welcome to the hiroba', 'Be kind.') returning id`);
await q(`select public.community_moderate('post', '${n1.id}', 'pin')`);
await q(`select public.community_moderate('post', '${p1.id}', 'lock')`);
feed = await q(`select * from public.community_feed(null, 'new', 30, 0, null)`);
ok('pinned staff post leads the feed', feed[0].title.startsWith('Welcome') && feed[0].pinned && feed[0].author_staff === true);
ok('staff sees reports', (await q(`select * from public.community_reports`)).length === 1);
await as('authenticated', B);
await fails('locked post refuses comments', `insert into public.community_comments (post_id, author_id, body) values (${p1.id}, '${B}', 'late')`, /closed/);
await as('authenticated', C);
await q(`select public.community_moderate('post', '${p1.id}', 'hide')`);
await q(`select public.community_moderate('member', '${B}', 'mute')`);
await as('authenticated', B);
ok('hidden post leaves the feed for others', (await q(`select * from public.community_feed('question', 'new', 30, 0, null)`)).length === 0 && (await q(`select public.community_thread(${p1.id}) t`))[0].t === null);
await fails('muted member cannot post', `insert into public.community_posts (author_id, category, title, body) values ('${B}', 'lounge', 'hello again', 'x')`, /muted/);
await as('authenticated', A);
ok('author still sees own hidden post', (await q(`select * from public.community_feed('question', 'new', 30, 0, null)`)).length === 1);
for (let i = 0; i < 7; i++) await q(`insert into public.community_posts (author_id, category, title, body) values ('${A}', 'lounge', 'post ${i}', 'x')`);
await fails('daily post limit', `insert into public.community_posts (author_id, category, title, body) values ('${A}', 'lounge', 'one too many', 'x')`, /limit/);
ok('A deletes own post, comments go too', (await db.query(`delete from public.community_posts where id = ${p1.id}`)).affectedRows === 1);
await as(null, '');
ok('cascade removed comments and likes', (await q(`select count(*)::int n from public.community_comments`))[0].n === 0 && (await q(`select count(*)::int n from public.community_likes`))[0].n === 0);
await as('anon', '');
await fails('anon cannot read posts', `select * from public.community_posts`);
await fails('anon cannot read the feed', `select * from public.community_feed(null, 'hot', 30, 0, null)`);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
